    void cleanupSwapChain() {
        vkDestroyImageView(device, depthImageView, nullptr);
        vkDestroyImage(device, depthImage, nullptr);
        vkFreeMemory(device, depthImageMemory, nullptr);

        for (auto framebuffer : swapChainFramebuffers) {
            vkDestroyFramebuffer(device, framebuffer, nullptr);
        }
        for (auto imageView : swapChainImageViews) {
            vkDestroyImageView(device, imageView, nullptr);
        }
        vkDestroySwapchainKHR(device, swapChain, nullptr);
    }

    void recreateSwapChain() {
        int width = 0, height = 0;
        glfwGetFramebufferSize(window, &width, &height);
        while (width == 0 || height == 0) {
            glfwGetFramebufferSize(window, &width, &height);
            glfwWaitEvents();
        }

        vkDeviceWaitIdle(device);

        cleanupSwapChain();

        createSwapChain();
        createImageViews();
        createDepthResources();
        createFramebuffers();
    }

    void updateAnimation() {
        auto now = std::chrono::steady_clock::now();
        float dt = std::chrono::duration<float>(now - lastFrameTime).count();
        lastFrameTime = now;
        if (animPlaying) {
            animTime += dt * animSpeed;
        }
    }

    glm::mat4 computeModelMatrix() {
        glm::vec3 basePos(objPosition[0], objPosition[1], objPosition[2]);
        glm::vec3 orbitOffset(0.0f);
        float extraYaw = 0.0f;
        if (animPlaying || animTime > 0.0f) {
            orbitOffset.x = cos(animTime) * animRadius;
            orbitOffset.z = sin(animTime) * animRadius;
            extraYaw = animTime;
        }

        glm::mat4 model = glm::translate(glm::mat4(1.0f), basePos + orbitOffset);
        model = glm::rotate(model, glm::radians(objRotationDeg[1]) + extraYaw, glm::vec3(0, 1, 0));
        model = glm::rotate(model, glm::radians(objRotationDeg[0]), glm::vec3(1, 0, 0));
        model = glm::rotate(model, glm::radians(objRotationDeg[2]), glm::vec3(0, 0, 1));
        model = glm::scale(model, glm::vec3(objScale[0], objScale[1], objScale[2]));
        return model;
    }

    void updateUniformBuffer(uint32_t currentImage) {
        GlobalUniforms ubo{};
        ubo.model = computeModelMatrix();
        ubo.view = glm::lookAt(glm::vec3(3.0f, 2.5f, 4.0f), glm::vec3(0.0f), glm::vec3(0.0f, 1.0f, 0.0f));

        float aspect = swapChainExtent.width / (float) swapChainExtent.height;
        if (usePerspective) {
            ubo.proj = glm::perspective(glm::radians(fovDegrees), aspect, 0.1f, 50.0f);
        } else {
            float orthoSize = 2.5f;
            ubo.proj = glm::ortho(-orthoSize * aspect, orthoSize * aspect, -orthoSize, orthoSize, -50.0f, 50.0f);
        }
        ubo.proj[1][1] *= -1;

        ubo.color = glm::vec4(objColor[0], objColor[1], objColor[2], objColor[3]);

        memcpy(uniformBuffersMapped[currentImage], &ubo, sizeof(ubo));
    }

